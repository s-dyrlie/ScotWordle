// Regenerates src/data/guesses.txt: every 6-letter English word that is
// allowed as a guess, from the SCOWL / English Speller Database word list.
//
// SCOWL writes proper nouns (names, places, days, ...) with a capital letter,
// so keeping only all-lowercase entries drops them. Possessives,
// hyphenated words and words with accents are dropped the same way.
//
// Usage: npm run build:guesses

import { writeFile, mkdir } from "node:fs/promises";

const WORD_LENGTH = 6;
const OUT = new URL("../src/data/guesses.txt", import.meta.url);

const params = new URLSearchParams([
    ["max_size", "80"], // "huge": includes uncommon words, slang and swears
    ["spelling", "US"],
    ["spelling", "GBs"],
    ["spelling", "GBz"],
    ["spelling", "CA"],
    ["spelling", "AU"],
    ["max_variant", "1"],
    ["diacritic", "strip"],
    ["download", "wordlist"],
    ["encoding", "utf-8"],
    ["format", "inline"],
]);
const SOURCE = `https://app.aspell.net/create?${params}`;

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`Download failed: ${res.status} ${res.statusText}`);
const text = await res.text();

// The download is "<licence header>\n---\n<one word per line>"
const sep = text.search(/^---$/m);
if (sep === -1) throw new Error("Unexpected format: no '---' separator found");
const header = text.slice(0, sep).trim();
const body = text.slice(sep + 3);

const pattern = new RegExp(`^[a-z]{${WORD_LENGTH}}$`);
const words = [...new Set(
    body.split(/\r?\n/).filter((w) => pattern.test(w)).map((w) => w.toUpperCase()),
)].sort();

if (words.length < 5000) throw new Error(`Only ${words.length} words found; refusing to write`);

const out = [
    "# Valid 6-letter guesses, generated by scripts/build-guesses.mjs. Do not edit by hand;",
    "# add extra words to EXTRA_GUESSES in src/words.ts instead.",
    "#",
    ...header.split(/\r?\n/).map((line) => `# ${line}`.trimEnd()),
    ...words,
].join("\n") + "\n";

await mkdir(new URL(".", OUT), { recursive: true });
await writeFile(OUT, out);
console.log(`Wrote ${words.length} words to src/data/guesses.txt`);
